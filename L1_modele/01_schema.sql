-- Création des tables de la coopérative
-- À lancer avec la connexion BDD-coop.
-- Le script peut être relancé : il supprime d'abord les tables.

BEGIN
    FOR t IN (SELECT table_name FROM user_tables
               WHERE table_name IN ('COMMANDE', 'COMMANDE_GROUPEE', 'PANIER', 'CLIENT', 'FERME'))
    LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- un site dépend du siège, le siège ne dépend de personne
CREATE TABLE FERME (
    ID_FERME        NUMBER(2)          NOT NULL,
    NOM             VARCHAR2(40 CHAR)  NOT NULL,
    VILLE           VARCHAR2(40 CHAR)  NOT NULL,
    ROLE            VARCHAR2(10 CHAR)  NOT NULL,
    ID_FERME_SIEGE  NUMBER(2),
    CONSTRAINT PK_FERME          PRIMARY KEY (ID_FERME),
    CONSTRAINT FK_FERME_SIEGE    FOREIGN KEY (ID_FERME_SIEGE) REFERENCES FERME (ID_FERME),
    CONSTRAINT CK_FERME_ROLE     CHECK (ROLE IN ('siège', 'site')),
    CONSTRAINT CK_FERME_DEPEND   CHECK ((ROLE = 'siège' AND ID_FERME_SIEGE IS NULL)
                                     OR (ROLE = 'site'  AND ID_FERME_SIEGE IS NOT NULL))
);

-- ID_CLIENT_PRINCIPAL : rempli quand la ligne est un doublon d'un autre client
CREATE TABLE CLIENT (
    ID_CLIENT            NUMBER(6)          NOT NULL,
    NOM                  VARCHAR2(40 CHAR)  NOT NULL,
    PRENOM               VARCHAR2(40 CHAR)  NOT NULL,
    EMAIL                VARCHAR2(100 CHAR),
    EMAIL_NORM           VARCHAR2(100 CHAR)
                         GENERATED ALWAYS AS (LOWER(REPLACE(EMAIL, ' ', ''))) VIRTUAL,
    TELEPHONE            VARCHAR2(20 CHAR),
    VILLE                VARCHAR2(40 CHAR)  NOT NULL,
    ID_FERME             NUMBER(2)          NOT NULL,
    DATE_INSCRIPTION     DATE               NOT NULL,
    ID_CLIENT_PRINCIPAL  NUMBER(6),
    CONSTRAINT PK_CLIENT            PRIMARY KEY (ID_CLIENT),
    CONSTRAINT FK_CLIENT_FERME      FOREIGN KEY (ID_FERME) REFERENCES FERME (ID_FERME),
    CONSTRAINT FK_CLIENT_PRINCIPAL  FOREIGN KEY (ID_CLIENT_PRINCIPAL) REFERENCES CLIENT (ID_CLIENT),
    CONSTRAINT CK_CLIENT_PRINCIPAL  CHECK (ID_CLIENT_PRINCIPAL <> ID_CLIENT)
);

CREATE TABLE PANIER (
    ID_PANIER      NUMBER(6)          NOT NULL,
    LIBELLE        VARCHAR2(60 CHAR)  NOT NULL,
    CATEGORIE      VARCHAR2(10 CHAR)  NOT NULL,
    ID_FERME       NUMBER(2)          NOT NULL,
    DEBUT          DATE               NOT NULL,
    DUREE_MINUTES  NUMBER(4)          NOT NULL,
    CAPACITE       NUMBER(4)          NOT NULL,
    PRIX_UNITAIRE  NUMBER(8,2)        NOT NULL,
    CONSTRAINT PK_PANIER            PRIMARY KEY (ID_PANIER),
    CONSTRAINT FK_PANIER_FERME      FOREIGN KEY (ID_FERME) REFERENCES FERME (ID_FERME),
    CONSTRAINT CK_PANIER_CATEGORIE  CHECK (CATEGORIE IN ('fromage', 'fruits', 'légumes', 'viande', 'mixte')),
    CONSTRAINT CK_PANIER_DUREE      CHECK (DUREE_MINUTES > 0),
    CONSTRAINT CK_PANIER_CAPACITE   CHECK (CAPACITE > 0),
    CONSTRAINT CK_PANIER_PRIX       CHECK (PRIX_UNITAIRE > 0)
);

CREATE TABLE COMMANDE_GROUPEE (
    ID_GROUPE  VARCHAR2(10 CHAR)  NOT NULL,
    CONSTRAINT PK_COMMANDE_GROUPEE PRIMARY KEY (ID_GROUPE)
);

-- pas de UNIQUE (ID_CLIENT, ID_PANIER) : un client peut commander deux fois le même panier
CREATE TABLE COMMANDE (
    ID_COMMANDE    NUMBER(7)          NOT NULL,
    ID_CLIENT      NUMBER(6)          NOT NULL,
    ID_PANIER      NUMBER(6)          NOT NULL,
    DATE_COMMANDE  DATE               NOT NULL,
    NB_PLACES      NUMBER(3)          NOT NULL,
    MONTANT        NUMBER(8,2)        NOT NULL,
    STATUT         VARCHAR2(10 CHAR)  NOT NULL,
    ID_GROUPE      VARCHAR2(10 CHAR),
    CONSTRAINT PK_COMMANDE          PRIMARY KEY (ID_COMMANDE),
    CONSTRAINT FK_COMMANDE_CLIENT   FOREIGN KEY (ID_CLIENT) REFERENCES CLIENT (ID_CLIENT),
    CONSTRAINT FK_COMMANDE_PANIER   FOREIGN KEY (ID_PANIER) REFERENCES PANIER (ID_PANIER),
    CONSTRAINT FK_COMMANDE_GROUPE   FOREIGN KEY (ID_GROUPE) REFERENCES COMMANDE_GROUPEE (ID_GROUPE),
    CONSTRAINT CK_COMMANDE_PLACES   CHECK (NB_PLACES >= 1),
    CONSTRAINT CK_COMMANDE_MONTANT  CHECK (MONTANT >= 0),
    CONSTRAINT CK_COMMANDE_STATUT   CHECK (STATUT IN ('CONFIRMEE', 'ANNULEE'))
);

-- index sur les clés étrangères
CREATE INDEX IX_FERME_SIEGE       ON FERME (ID_FERME_SIEGE);
CREATE INDEX IX_CLIENT_FERME      ON CLIENT (ID_FERME);
CREATE INDEX IX_CLIENT_PRINCIPAL  ON CLIENT (ID_CLIENT_PRINCIPAL);
CREATE INDEX IX_PANIER_FERME      ON PANIER (ID_FERME);
CREATE INDEX IX_COMMANDE_CLIENT   ON COMMANDE (ID_CLIENT);
CREATE INDEX IX_COMMANDE_PANIER   ON COMMANDE (ID_PANIER);
CREATE INDEX IX_COMMANDE_GROUPE   ON COMMANDE (ID_GROUPE);

-- vérification
SELECT table_name FROM user_tables ORDER BY table_name;

SELECT table_name, constraint_name, constraint_type
  FROM user_constraints
 WHERE constraint_name NOT LIKE 'SYS%'
 ORDER BY table_name, constraint_name;
